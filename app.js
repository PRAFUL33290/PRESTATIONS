function sortPrestations(list, mode) {
  const copy = [...list];
  switch (mode) {
    case "event-desc":
      return copy.sort((a, b) => b.eventDate.localeCompare(a.eventDate));
    case "deadline-asc":
      return copy.sort((a, b) => {
        if (!a.deadline && !b.deadline) return a.eventDate.localeCompare(b.eventDate);
        if (!a.deadline) return 1;
        if (!b.deadline) return -1;
        return a.deadline.localeCompare(b.deadline);
      });
    case "name-asc":
      return copy.sort((a, b) => a.client.localeCompare(b.client, "fr"));
    case "event-asc":
    default:
      return copy.sort((a, b) => a.eventDate.localeCompare(b.eventDate));
  }
}

function filterPrestations(list, query, status) {
  const q = query.trim().toLowerCase();
  return list.filter((item) => {
    if (status !== "all" && item.status !== status) return false;
    if (!q) return true;
    const haystack = [
      item.title,
      item.client,
      item.organisation,
      item.lieu,
      item.type,
      item.notes,
      item.priceMain,
      item.devisNumero,
      item.contactEmail,
      item.contactEmailSecondary,
      item.contactName,
      item.devisVersion,
      item.speechBy,
      item.speechFr,
      item.speechEn,
      item.dancersLabel,
      item.validationMessage,
      item.deadlineNote,
      ...(item.tags || []),
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}


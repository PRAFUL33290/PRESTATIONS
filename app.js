function parseDate(iso) {
  if (!iso) return null;
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
}

function formatDateLong(iso) {
  const date = parseDate(iso);
  if (!date) return "—";
  return `${date.getDate()} ${MONTHS_FR[date.getMonth()]} ${date.getFullYear()}`;
}

function formatDateShort(iso) {
  const date = parseDate(iso);
  if (!date) return "—";
  return `${String(date.getDate()).padStart(2, "0")}/${String(date.getMonth() + 1).padStart(2, "0")}/${date.getFullYear()}`;
}

function daysUntil(iso) {
  const target = parseDate(iso);
  if (!target) return null;
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  target.setHours(0, 0, 0, 0);
  return Math.round((target - today) / (1000 * 60 * 60 * 24));
}

function relativeLabel(iso) {
  const n = daysUntil(iso);
  if (n === null) return "";
  if (n < 0) return `Il y a ${Math.abs(n)} j`;
  if (n === 0) return "Aujourd'hui";
  if (n === 1) return "Demain";
  return `Dans ${n} j`;
}

/** Libellé explicite du nombre de jours restants (basé sur la date du jour). */
function daysRemainingLabel(iso) {
  const n = daysUntil(iso);
  if (n === null) return "";
  if (n < 0) {
    const d = Math.abs(n);
    return d === 1 ? "Dépassé d’1 jour" : `Dépassé de ${d} jours`;
  }
  if (n === 0) return "Aujourd’hui — 0 jour restant";
  if (n === 1) return "1 jour restant";
  return `${n} jours restants`;
}

/** Classe CSS selon l’urgence du délai. */
function countdownTone(iso, urgent = false) {
  const n = daysUntil(iso);
  if (n === null) return "countdown-neutral";
  if (n < 0) return "countdown-past";
  if (urgent || n <= 7) return "countdown-urgent";
  if (n <= 30) return "countdown-soon";
  return "countdown-ok";
}

function countdownBadge(iso, { urgent = false, prefix = "" } = {}) {
  const label = daysRemainingLabel(iso);
  if (!label) return "";
  const tone = countdownTone(iso, urgent);
  const text = prefix ? `${prefix} · ${label}` : label;
  return `<span class="countdown ${tone}">${escapeHtml(text)}</span>`;
}

/** Extrait un montant en euros depuis un libellé FR (ex. "452,00 € TTC", "704 € (estimé)"). */
function parsePriceEuro(str) {
  if (!str) return null;
  const raw = String(str).trim();
  if (!/\d/.test(raw)) return null;
  if (/incertain|à définir|a definir|n\/a/i.test(raw) && !/\d+[.,]?\d*\s*€/.test(raw)) {
    return null;
  }
  const match = raw.match(/(\d{1,3}(?:[.\s]\d{3})*(?:,\d+)?|\d+(?:,\d+)?)/);
  if (!match) return null;
  const normalized = match[1].replace(/[\s.]/g, "").replace(",", ".");
  const n = Number(normalized);
  return Number.isFinite(n) ? n : null;
}

function formatPriceEuro(amount) {
  return new Intl.NumberFormat("fr-FR", {
    style: "currency",
    currency: "EUR",
  }).format(amount);
}

function sumPrices(list) {
  let total = 0;
  let counted = 0;
  let estimated = 0;
  for (const item of list) {
    const amount = parsePriceEuro(item.priceMain);
    if (amount === null) continue;
    total += amount;
    counted += 1;
    if (/estimé|estime/i.test(item.priceMain || "")) estimated += 1;
  }
  return { total, counted, estimated };
}

